/// Which of the brain's memory notes are behaviors, and where they go.
/// The rest (facts) stay memory.
pub const FROM_MEMORY: &[(&str, &str)] = &[
    ("autonomy-for-space-sessions", "Questions 90/10"),
    ("be-brief-simple-tasks", "Talking"),
    ("say-what-blocked-needs", "Talking"),
    ("name-sessions-at-startup", "Sessions"),
    ("dev-ports-3000-3050", "Sessions"),
    ("open-sessions-in-named-space", "Spaces and focus"),
    ("release-dev-then-prod", "Releases and safety"),
    ("validate-everything", "Releases and safety"),
    ("open-in-brave", "Browsers"),
    ("dashboard-means-eyzflow", "Misc"),
];

/// A memory note's frontmatter `description` and its body.
fn memory_note(text: &str) -> (String, String) {
    let Some(rest) = text.strip_prefix("---\n") else { return (String::new(), text.trim().to_string()) };
    let Some((head, body)) = rest.split_once("\n---\n") else { return (String::new(), text.trim().to_string()) };
    let description = head
        .lines()
        .find_map(|l| l.strip_prefix("description:"))
        .map(|d| {
            let d = d.trim();
            // A quoted YAML string; a value that only starts with a quoted word stays as it is.
            if d.len() > 1 && d.starts_with('"') && d.ends_with('"') { d[1..d.len() - 1].replace("\\\"", "\"") } else { d.to_string() }
        })
        .unwrap_or_default();
    (description, body.trim().to_string())
}

/// `be-brief-simple-tasks` -> "Be brief simple tasks"; the note's own title line wins.
fn title_of(name: &str, description: &str) -> String {
    let t = name.replace('-', " ");
    let mut c = t.chars();
    let titled: String = c.next().map(|f| f.to_uppercase().chain(c).collect()).unwrap_or_default();
    if titled.len() < 4 { description.to_string() } else { titled }
}

/// Moves the brain's memory notes that are behaviors into the store
/// (source `learned`, full text kept), the originals into
/// `behaviors/.migrated/`, and their lines out of `MEMORY.md`.
pub fn migrate_memory(store: &Store, memory: &Path) -> Result<Vec<String>> {
    let mut moved = vec![];
    let keep = store.dir.join(".migrated");
    // The index names each note: `- [Browser per account](open-in-brave.md) — …`.
    let index = std::fs::read_to_string(memory.join("MEMORY.md")).unwrap_or_default();
    let named = |file: &str| -> Option<String> {
        index.lines().find(|l| l.contains(&format!("({file})"))).and_then(|l| l.split_once('[')).and_then(|(_, r)| r.split_once(']')).map(|(t, _)| t.trim().to_string())
    };
    for (name, category) in FROM_MEMORY {
        let src = memory.join(format!("{name}.md"));
        let Ok(text) = std::fs::read_to_string(&src) else { continue };
        let (description, body) = memory_note(&text);
        if body.is_empty() {
            continue;
        }
        let title = named(&format!("{name}.md")).unwrap_or_else(|| title_of(name, &description));
        let (b, _) = store.add(&title, category, &description, &body, "learned", "tower")?;
        std::fs::create_dir_all(&keep)?;
        std::fs::rename(&src, keep.join(format!("{name}.md"))).with_context(|| format!("moving {}", src.display()))?;
        moved.push(b.id);
    }
    if !moved.is_empty() {
        let index = memory.join("MEMORY.md");
        if let Ok(text) = std::fs::read_to_string(&index) {
            let _ = std::fs::write(keep.join("MEMORY.md.before"), &text);
            let kept: Vec<&str> = text.lines().filter(|l| !FROM_MEMORY.iter().any(|(n, _)| l.contains(&format!("({n}.md)")))).collect();
            std::fs::write(&index, kept.join("\n") + "\n")?;
        }
    }
    Ok(moved)
}

/// The brain's memory folder (Claude Code's, for the brain's folder).
pub fn brain_memory_dir() -> PathBuf {
    let dir = crate::config::brain_dir();
    let escaped: String = dir.to_string_lossy().chars().map(|c| if c.is_ascii_alphanumeric() { c } else { '-' }).collect();
    crate::config::home().join(".claude/projects").join(escaped).join("memory")
}

