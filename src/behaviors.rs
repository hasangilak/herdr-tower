const GENERATED: &str = "<!-- Generated by the tower from its core and your behaviors. Don't edit this file: change behaviors in the panel, on the phone, with `tower behavior`, or by telling the tower. -->";

#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct Behavior {
    pub id: String,
    pub title: String,
    pub category: String,
    pub enabled: bool,
    /// `builtin` (came with the tower), `user` (the user added it), `learned` (from the brain's memory or what the user said).
    pub source: String,
    /// One plain sentence for the user.
    pub summary: String,
    pub created_ms: u64,
    pub updated_ms: u64,
    /// For a builtin: the text as it shipped, so an unedited one can follow a new version.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub builtin_hash: Option<String>,
    /// The rule itself, as the brain reads it (markdown).
    pub text: String,
}

fn now_ms() -> u64 {
    crate::history::now_ms()
}

fn hash(text: &str) -> String {
    crate::daemon::lan::auth::sha256_hex(text.trim().as_bytes())[..16].to_string()
}

/// `---\nkey: value\n---\n\ntext`.
pub fn parse(file: &str) -> Option<Behavior> {
    let rest = file.strip_prefix("---\n")?;
    let (head, text) = rest.split_once("\n---\n")?;
    let mut b = Behavior { enabled: true, text: text.trim().to_string() + "\n", ..Default::default() };
    for line in head.lines() {
        let Some((k, v)) = line.split_once(':') else { continue };
        let v = v.trim().to_string();
        match k.trim() {
            "id" => b.id = v,
            "title" => b.title = v,
            "category" => b.category = v,
            "enabled" => b.enabled = v != "false",
            "source" => b.source = v,
            "summary" => b.summary = v,
            "created_ms" => b.created_ms = v.parse().unwrap_or(0),
            "updated_ms" => b.updated_ms = v.parse().unwrap_or(0),
            "builtin_hash" => b.builtin_hash = Some(v).filter(|v| !v.is_empty()),
            _ => {}
        }
    }
    (!b.id.is_empty()).then_some(b)
}

fn one_line(s: &str) -> String {
    s.split_whitespace().collect::<Vec<_>>().join(" ")
}

pub fn render(b: &Behavior) -> String {
    let mut s = format!(
        "---\nid: {}\ntitle: {}\ncategory: {}\nenabled: {}\nsource: {}\nsummary: {}\ncreated_ms: {}\nupdated_ms: {}\n",
        b.id,
        one_line(&b.title),
        one_line(&b.category),
        b.enabled,
        b.source,
        one_line(&b.summary),
        b.created_ms,
        b.updated_ms
    );
    if let Some(h) = &b.builtin_hash {
        s += &format!("builtin_hash: {h}\n");
    }
    s += "---\n\n";
    s += b.text.trim();
    s += "\n";
    s
}

/// `Use Brave for orca` -> `use-brave-for-orca`.
pub fn slug(title: &str) -> String {
    let s: String = title.to_lowercase().chars().map(|c| if c.is_ascii_alphanumeric() { c } else { '-' }).collect();
    let s = s.split('-').filter(|p| !p.is_empty()).take(8).collect::<Vec<_>>().join("-");
    if s.is_empty() { "behavior".into() } else { s }
}

/// A category the store knows (a close spelling is fine); anything else is Misc.
pub fn category_of(c: &str) -> String {
    let n = c.trim().to_lowercase();
    CATEGORIES
        .iter()
        .find(|k| k.to_lowercase() == n || (n.len() > 3 && k.to_lowercase().starts_with(&n)) || (n.contains("question") && k.starts_with("Questions")))
        .map(|k| k.to_string())
        .unwrap_or_else(|| "Misc".into())
}

/// Lines of `before` and `after`: `  ` same, `- ` gone, `+ ` new.
pub fn diff(before: &str, after: &str) -> String {
    let a: Vec<&str> = before.lines().collect();
    let b: Vec<&str> = after.lines().collect();
    let (n, m) = (a.len(), b.len());
    let mut lcs = vec![vec![0usize; m + 1]; n + 1];
    for i in (0..n).rev() {
        for j in (0..m).rev() {
            lcs[i][j] = if a[i] == b[j] { lcs[i + 1][j + 1] + 1 } else { lcs[i + 1][j].max(lcs[i][j + 1]) };
        }
    }
    let (mut i, mut j) = (0, 0);
    let mut out = vec![];
    while i < n || j < m {
        if i < n && j < m && a[i] == b[j] {
            out.push(format!("  {}", a[i]));
            i += 1;
            j += 1;
        } else if j < m && (i == n || lcs[i][j + 1] >= lcs[i + 1][j]) {
            out.push(format!("+ {}", b[j]));
            j += 1;
        } else {
            out.push(format!("- {}", a[i]));
            i += 1;
        }
    }
    out.join("\n")
}

/// What may change in an edit.
#[derive(Debug, Clone, Default, Deserialize)]
#[serde(default)]
pub struct Patch {
    pub title: Option<String>,
    pub category: Option<String>,
    pub summary: Option<String>,
    pub text: Option<String>,
    pub enabled: Option<bool>,
}

/// A change, as the history keeps it.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct Change {
    pub at: u64,
    /// add, edit, enable, disable, remove, undo, seed, migrate.
    pub op: String,
    pub id: String,
    pub title: String,
    /// The file before (None: it didn't exist) and after (None: removed).
    pub before: Option<String>,
    pub after: Option<String>,
    /// Who: `user` (panel, phone, terminal), `brain`, `tower`.
    pub by: String,
    /// An undo: which change (its `at`) it undid.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub undid: Option<u64>,
}

impl Change {
    /// The change in a line, and its diff, for the chat and the history.
    pub fn view(&self) -> Value {
        let text = |f: &Option<String>| f.as_deref().and_then(parse).map(|b| b.text).unwrap_or_default();
        json!({
            "at": self.at, "op": self.op, "id": self.id, "title": self.title, "by": self.by, "undid": self.undid,
            "diff": diff(&text(&self.before), &text(&self.after)),
        })
    }
}

pub struct Store {
    pub dir: PathBuf,
}

impl Store {
    pub fn path() -> PathBuf {
        crate::config::config_dir().join("behaviors")
    }

    pub fn open() -> Store {
        Store { dir: Self::path() }
    }

    fn file(&self, id: &str) -> PathBuf {
        self.dir.join(format!("{id}.md"))
    }

    /// Every behavior, by category (in `CATEGORIES` order), then title.
    pub fn list(&self) -> Vec<Behavior> {
        let mut v: Vec<Behavior> = std::fs::read_dir(&self.dir)
            .into_iter()
            .flatten()
            .flatten()
            .filter(|e| e.path().extension().is_some_and(|x| x == "md"))
            .filter_map(|e| std::fs::read_to_string(e.path()).ok().and_then(|t| parse(&t)))
            .collect();
        let rank = |c: &str| CATEGORIES.iter().position(|k| *k == c).unwrap_or(CATEGORIES.len());
        v.sort_by(|a, b| (rank(&a.category), a.created_ms, &a.title).cmp(&(rank(&b.category), b.created_ms, &b.title)));
        v
    }

    pub fn get(&self, id: &str) -> Option<Behavior> {
        if id.contains('/') || id.contains("..") {
            return None;
        }
        std::fs::read_to_string(self.file(id)).ok().and_then(|t| parse(&t))
    }

    fn raw(&self, id: &str) -> Option<String> {
        std::fs::read_to_string(self.file(id)).ok()
    }

    /// Writes a behavior (or removes it: `None`) and logs the change.
    fn put(&self, id: &str, after: Option<&Behavior>, op: &str, by: &str, undid: Option<u64>) -> Result<Change> {
        std::fs::create_dir_all(&self.dir)?;
        let before = self.raw(id);
        let after_text = after.map(render);
        match &after_text {
            Some(t) => {
                let tmp = self.dir.join(format!(".{id}.tmp"));
                std::fs::write(&tmp, t)?;
                std::fs::rename(&tmp, self.file(id))?;
            }
            None => {
                let _ = std::fs::remove_file(self.file(id));
            }
        }
        let title = after.map(|b| b.title.clone()).or_else(|| before.as_deref().and_then(parse).map(|b| b.title)).unwrap_or_default();
        let c = Change { at: now_ms(), op: op.into(), id: id.into(), title, before, after: after_text, by: by.into(), undid };
        let mut f = std::fs::OpenOptions::new().create(true).append(true).open(self.dir.join("history.jsonl"))?;
        writeln!(f, "{}", serde_json::to_string(&c)?)?;
        Ok(c)
    }

    pub fn history(&self) -> Vec<Change> {
        std::fs::read_to_string(self.dir.join("history.jsonl"))
            .unwrap_or_default()
            .lines()
            .filter_map(|l| serde_json::from_str(l).ok())
            .collect()
    }

    pub fn add(&self, title: &str, category: &str, summary: &str, text: &str, source: &str, by: &str) -> Result<(Behavior, Change)> {
        let title = one_line(title);
        if title.is_empty() || text.trim().is_empty() {
            bail!("a behavior needs a title and its text");
        }
        let base = slug(&title);
        let mut id = base.clone();
        let mut k = 2;
        while self.file(&id).exists() {
            id = format!("{base}-{k}");
            k += 1;
        }
        let now = now_ms();
        let b = Behavior {
            id: id.clone(),
            title,
            category: category_of(category),
            enabled: true,
            source: source.into(),
            summary: one_line(summary),
            created_ms: now,
            updated_ms: now,
            builtin_hash: None,
            text: text.trim().to_string() + "\n",
        };
        let c = self.put(&id, Some(&b), "add", by, None)?;
        Ok((b, c))
    }

    pub fn edit(&self, id: &str, p: &Patch, by: &str) -> Result<(Behavior, Change)> {
        let Some(mut b) = self.get(id) else { bail!("no behavior {id}") };
        if let Some(t) = &p.title {
            b.title = one_line(t);
        }
        if let Some(c) = &p.category {
            b.category = category_of(c);
        }
        if let Some(s) = &p.summary {
            b.summary = one_line(s);
        }
        if let Some(t) = &p.text {
            if t.trim().is_empty() {
                bail!("a behavior's text can't be empty (disable or remove it instead)");
            }
            b.text = t.trim().to_string() + "\n";
        }
        let op = match (p.enabled, p.title.is_some() || p.category.is_some() || p.summary.is_some() || p.text.is_some()) {
            (Some(e), false) => {
                b.enabled = e;
                if e { "enable" } else { "disable" }
            }
            (e, _) => {
                if let Some(e) = e {
                    b.enabled = e;
                }
                "edit"
            }
        };
        b.updated_ms = now_ms();
        let c = self.put(id, Some(&b), op, by, None)?;
        Ok((b, c))
    }

    pub fn remove(&self, id: &str, by: &str) -> Result<Change> {
        if self.get(id).is_none() {
            bail!("no behavior {id}");
        }
        self.put(id, None, "remove", by, None)
    }

    /// Undoes the latest change not undone yet; undo again to go further back.
    pub fn undo(&self, by: &str) -> Result<Change> {
        let h = self.history();
        let undone: Vec<u64> = h.iter().filter_map(|c| c.undid).collect();
        let Some(last) = h.iter().rev().find(|c| !undone.contains(&c.at) && !matches!(c.op.as_str(), "seed" | "migrate" | "undo")) else {
            bail!("nothing to undo")
        };
        let restored = last.before.as_deref().and_then(parse);
        self.put(&last.id, restored.as_ref(), "undo", by, Some(last.at))
    }

    /// The builtins that are missing; and unedited builtins that changed in this release.
    pub fn seed(&self) -> Result<Vec<String>> {
        let mut done = vec![];
        let now = now_ms();
        for raw in BUILTIN {
            let Some(mut b) = parse(raw) else { continue };
            let h = hash(&b.text);
            b.builtin_hash = Some(h.clone());
            match self.get(&b.id) {
                None => {
                    // Removed on purpose earlier: leave it removed.
                    if self.history().iter().any(|c| c.id == b.id && c.op == "remove") {
                        continue;
                    }
                    b.created_ms = now;
                    b.updated_ms = now;
                    self.put(&b.id, Some(&b), "seed", "tower", None)?;
                    done.push(b.id);
                }
                Some(cur) if cur.source == "builtin" && cur.builtin_hash.as_deref() == Some(&hash(&cur.text)) && cur.builtin_hash.as_deref() != Some(&h) => {
                    // Unedited, and the tower's text moved on: follow it (keeping on/off).
                    b.created_ms = cur.created_ms;
                    b.updated_ms = now;
                    b.enabled = cur.enabled;
                    self.put(&b.id, Some(&b), "seed", "tower", None)?;
                    done.push(b.id);
                }
                _ => {}
            }
        }
        Ok(done)
    }

    /// The brain's instructions: the core, then every enabled behavior by category.
    pub fn prompt(&self) -> String {
        let mut s = format!("{GENERATED}\n\n{}\n\n# Behaviors\n", CORE.trim());
        let list = self.list();
        let mut last = String::new();
        for b in list.iter().filter(|b| b.enabled) {
            if b.category != last {
                s += &format!("\n## {}\n", b.category);
                last = b.category.clone();
            }
            s += &format!("\n### {}\n\n{}", b.title, b.text.trim_end());
            s += "\n";
        }
        s
    }

    /// For the state and the UIs: how many, by category.
    pub fn summary(&self) -> Value {
        let list = self.list();
        let by: serde_json::Map<String, Value> = CATEGORIES
            .iter()
            .map(|c| (c.to_string(), json!(list.iter().filter(|b| b.category == *c).count())))
            .filter(|(_, n)| n != &json!(0))
            .collect();
        json!({
            "count": list.len(),
            "enabled": list.iter().filter(|b| b.enabled).count(),
            "by_category": by,
            "updated_ms": list.iter().map(|b| b.updated_ms).max().unwrap_or(0),
        })
    }
}

// ---- changing them (the CLI, the phone API, the panel through the daemon) ----

/// One change to the behaviors.
#[derive(Debug, Clone)]
pub enum Op {
    Add { title: String, category: String, summary: String, text: String },
    Edit { id: String, patch: Patch },
    Remove { id: String },
    Undo,
}

/// Applies a change and regenerates the brain's instructions. `by`: `user`, `brain`.
pub fn apply(op: Op, by: &str) -> Result<(Option<Behavior>, Change)> {
    let store = Store::open();
    let source = if by == "brain" { "learned" } else { "user" };
    let (b, c) = match op {
        Op::Add { title, category, summary, text } => {
            let (b, c) = store.add(&title, &category, &summary, &text, source, by)?;
            (Some(b), c)
        }
        Op::Edit { id, patch } => {
            let (b, c) = store.edit(&id, &patch, by)?;
            (Some(b), c)
        }
        Op::Remove { id } => (None, store.remove(&id, by)?),
        Op::Undo => {
            let c = store.undo(by)?;
            (store.get(&c.id), c)
        }
    };
    crate::brain::write_prompt()?;
    Ok((b, c))
}

/// Who is changing them: the brain (from its own terminal) or the user.
pub fn caller() -> &'static str {
    let me = std::env::var("HC_TERMINAL_ID").unwrap_or_default();
    if me.is_empty() {
        return "user";
    }
    let brain = crate::hc::get(&crate::brain::name()).and_then(|t| t["address"].as_str().map(String::from)).unwrap_or_default();
    if me == brain { "brain" } else { "user" }
}

/// What the UIs show: the categories, every behavior, the fixed core, a summary.
pub fn listing() -> Value {
    let store = Store::open();
    json!({
        "categories": CATEGORIES,
        "behaviors": store.list(),
        "core": { "title": "How the tower works (fixed)", "text": CORE, "read_only": true },
        "summary": store.summary(),
    })
}

