    #[test]
    fn memory_notes_become_learned_behaviors() {
        let s = store("memory");
        let mem = s.dir.with_extension("mem");
        let _ = std::fs::remove_dir_all(&mem);
        std::fs::create_dir_all(&mem).unwrap();
        std::fs::write(
            mem.join("release-dev-then-prod.md"),
            "---\nname: release-dev-then-prod\ndescription: Releases always go to dev first, then dev to prod\nmetadata:\n  type: feedback\n---\n\nAlways release via dev first.\n\n**Why:** standing rule.\n",
        )
        .unwrap();
        std::fs::write(mem.join("email-setup-already-done.md"), "---\nname: email\n---\n\nA fact.\n").unwrap();
        std::fs::write(
            mem.join("MEMORY.md"),
            "- [Release dev then prod](release-dev-then-prod.md) — dev first\n- [Email setup already done](email-setup-already-done.md) — fact\n",
        )
        .unwrap();
        let moved = migrate_memory(&s, &mem).unwrap();
        assert_eq!(moved, ["release-dev-then-prod"]);
        let b = s.get("release-dev-then-prod").unwrap();
        assert_eq!((b.category.as_str(), b.source.as_str(), b.summary.as_str()), ("Releases and safety", "learned", "Releases always go to dev first, then dev to prod"));
        assert_eq!(b.title, "Release dev then prod", "the title from the memory index");
        assert_eq!(memory_note("---\ndescription: \"dashboard\" means eyzflow\n---\nx").0, "\"dashboard\" means eyzflow");
        assert_eq!(memory_note("---\ndescription: \"all quoted\"\n---\nx").0, "all quoted");
        assert!(b.text.contains("**Why:** standing rule."), "the whole text is kept");
        assert!(!mem.join("release-dev-then-prod.md").exists() && s.dir.join(".migrated/release-dev-then-prod.md").exists());
        assert!(mem.join("email-setup-already-done.md").exists(), "facts stay memory");
        let index = std::fs::read_to_string(mem.join("MEMORY.md")).unwrap();
        assert!(!index.contains("release-dev-then-prod") && index.contains("email-setup-already-done"));
        assert!(migrate_memory(&s, &mem).unwrap().is_empty(), "once");
        let _ = std::fs::remove_dir_all(&s.dir);
        let _ = std::fs::remove_dir_all(&mem);
    }

